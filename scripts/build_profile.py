#!/usr/bin/env python3
"""Build README.md and assets/hero.svg from scripts/content.py.

Usage:
    python scripts/build_profile.py          # write the files
    python scripts/build_profile.py --check  # fail if the files are stale

The build is deterministic: no dates, no API calls, no random values. That
makes `--check` safe to run in CI on every push.
"""

from __future__ import annotations

import argparse
import html
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

import content
from svg_hero import build_hero_svg

ROOT = Path(__file__).resolve().parent.parent
README_PATH = ROOT / "README.md"
HERO_PATH = ROOT / "assets" / "hero.svg"


def _projects_markdown() -> str:
    return "\n\n".join(
        f"**[{project.name}]({project.url})** {project.body}"
        for project in content.PROJECTS
    )


def _roles_markdown() -> str:
    return "\n".join(
        f"- **{role.title}**, {role.org}. {role.period}. {role.detail}"
        for role in content.ROLES
    )


def _links_markdown() -> str:
    parts = [f"[{label}]({url})" for label, url in content.LINKS]
    return " · ".join(parts)


def build_readme() -> str:
    hero = (
        '<div align="center">\n'
        f'  <img src="assets/hero.svg" alt="{html.escape(content.HERO_ALT, quote=True)}" width="100%">\n'
        "</div>"
    )

    blocks = [
        "<!-- Generated by scripts/build_profile.py. Edit scripts/content.py instead. -->",
        hero,
        content.INTRO,
        "## What I'm building",
        _projects_markdown(),
        content.SMALLER,
        "## Where I've worked",
        _roles_markdown(),
        "## Elsewhere",
        content.CREDENTIALS,
        _links_markdown(),
        content.CLOSING,
    ]
    return "\n\n".join(blocks) + "\n"


def _compare_or_write(path: Path, value: str, check: bool) -> bool:
    """Return True when the file is current. Write it when not checking."""
    current = path.read_text(encoding="utf-8") if path.exists() else None
    if current == value:
        print(f"[build] current  {path.relative_to(ROOT)}")
        return True

    if check:
        print(f"[build] stale    {path.relative_to(ROOT)}")
        return False

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(value, encoding="utf-8", newline="\n")
    print(f"[build] wrote    {path.relative_to(ROOT)}")
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; exit non-zero when a generated file is out of date",
    )
    args = parser.parse_args()

    hero = build_hero_svg()
    # Fail before touching disk if the template produced invalid XML.
    ET.fromstring(hero)

    fresh = [
        _compare_or_write(README_PATH, build_readme(), args.check),
        _compare_or_write(HERO_PATH, hero, args.check),
    ]

    if not all(fresh):
        print(
            "[build] Generated files are out of date. "
            "Run `python scripts/build_profile.py` and commit the result.",
            file=sys.stderr,
        )
        return 1

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
